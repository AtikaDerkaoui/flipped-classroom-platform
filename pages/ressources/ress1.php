<h1>Comprendre la classe inversée</h1>

<section>
<h2>Qu'est-ce que la classe inversée ?</h2>
<p>
    La classe inversée (ou flipped classroom) est une méthode pédagogique innovante 
    qui renverse l'organisation traditionnelle des cours. Au lieu de découvrir les 
    leçons en classe et faire les exercices à la maison, les élèves consultent le 
    contenu théorique chez eux, puis réalisent des activités pratiques en classe.
</p>
</section>

<section>
<h2>Objectif principal</h2>
<p>L'objectif est de rendre l'élève actif dans son apprentissage. Cela permet :</p>
<ul>
    <li>de libérer du temps en classe pour les échanges et les travaux de groupe,</li>
    <li>d'adapter l'accompagnement aux besoins de chacun,</li>
    <li>d'encourager l'autonomie et la responsabilisation.</li>
</ul>
</section>

<section>
<h2>Comment fonctionne la classe inversée ?</h2>
<p>Le déroulement se fait généralement en deux temps :</p>
<ol>
    <li><strong>À la maison :</strong> l'élève découvre les notions via une capsule vidéo, un document ou un podcast.</li>
    <li><strong>En classe :</strong> le temps est utilisé pour poser des questions, faire des exercices, collaborer avec les autres ou bénéficier de l’aide du professeur.</li>
</ol>
</section>

<section>
<h2>Avantages de la classe inversée</h2>
<ul>
    <li>Améliore la compréhension grâce à un rythme adapté à chaque élève.</li>
    <li>Libère du temps pour l'interaction et l'approfondissement.</li>
    <li>Renforce l'autonomie et la responsabilisation.</li>
    <li>Favorise l'apprentissage actif.</li>
</ul>
</section>

<section>
<h2>Conclusion</h2>
<p>
    La classe inversée transforme la posture de l'enseignant et des élèves. 
    Elle offre une nouvelle dynamique où les élèves deviennent acteurs de leur apprentissage, 
    tout en rendant les séances en présentiel plus riches et efficaces.
</p>
</section>
